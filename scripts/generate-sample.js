function generate(p) {
  const rnd = mulberry32(p.seed);
  const gauss = () => {
    const u = 1 - rnd(), v = rnd();
    return Math.sqrt(-2 * Math.log(u)) * Math.cos(2 * Math.PI * v);
  };
  // Triangular distribution sample on [a, b] with mode c.
  const tri = (a, b, c) => {
    const u = rnd(), f = (c - a) / (b - a);
    return u < f ? a + Math.sqrt(u * (b - a) * (c - a)) : b - Math.sqrt((1 - u) * (b - a) * (b - c));
  };
  const t0 = Date.parse(p.start);
  const KM_LAT = 111.2;
  const kmLon = (lat) => 111.32 * Math.cos((lat * Math.PI) / 180);
  const raw = [];
  const intensity = (type) => (type === "CG" ? 0.35 + 0.6 * Math.pow(rnd(), 1.4) : 0.1 + 0.45 * rnd());

  for (const c of p.cells) {
    const h = (c.headingDeg * Math.PI) / 180;
    for (let i = 0; i < c.n; i++) {
      const min = tri(c.from, c.to, c.peak);
      const travelKm = ((min - c.from) / 60) * c.kmh;
      const lat = c.lat + (travelKm * Math.cos(h) + gauss() * c.sigmaKm) / KM_LAT;
      const lon = c.lon + (travelKm * Math.sin(h) + gauss() * c.sigmaKm) / kmLon(c.lat);
      const type = rnd() < c.cg ? "CG" : "IC";
      raw.push({ cell: c.label, ms: t0 + Math.round(min * 60) * 1000, lat, lon, type, intensity: intensity(type) });
    }
  }
  for (let i = 0; i < p.isolated; i++) {
    const type = rnd() < 0.5 ? "CG" : "IC";
    raw.push({
      cell: "isolated",
      ms: t0 + Math.round(rnd() * p.minutes * 60) * 1000,
      lat: p.bbox.south + rnd() * (p.bbox.north - p.bbox.south),
      lon: p.bbox.west + rnd() * (p.bbox.east - p.bbox.west),
      type, intensity: intensity(type),
    });
  }
  if (p.tiePair) {
    const inCell = raw.filter((r) => r.cell === p.tiePair);
    inCell[1].ms = inCell[0].ms; // simultaneous strikes at different places
  }
  raw.sort((a, b) => a.ms - b.ms);
  const events = raw.map((r, i) => {
    const e = {
      id: `strike-${String(i + 1).padStart(3, "0")}`,
      timestamp: toIsoWithOffset(r.ms, p.offsetMin),
      lat: Math.round(r.lat * 1e4) / 1e4,
      lon: Math.round(r.lon * 1e4) / 1e4,
      type: r.type,
    };
    if (!p.noIntensity) e.intensity = Math.round(r.intensity * 100) / 100;
    return e;
  });
  const meta = {
    name: p.name,
    synthetic: true,
    description:
      "FICTIONAL storm generated by scripts/generate-sample.js for testing. These events were not detected by any lightning network.",
    generator: "scripts/generate-sample.js",
    seed: p.seed,
    windowStart: toIsoWithOffset(t0, p.offsetMin),
    windowEnd: toIsoWithOffset(t0 + p.minutes * 60000, p.offsetMin),
    utcOffset: p.offsetMin === 0 ? "Z" : toIsoWithOffset(0, p.offsetMin).slice(19),
    ...(p.noIntensity ? {} : { intensityNormalized: true, intensityNote: "Synthetic 0–1 visual weight, not a physical amplitude." }),
  };
  return { meta, events };
}

function toCsv({ meta, events }) {
  const lines = Object.entries(meta).map(([k, v]) => `# ${k}: ${v}`);
  const cols = Object.keys(events[0]);
  lines.push(cols.join(","));
  for (const e of events) lines.push(cols.map((c) => e[c]).join(","));
  return lines.join("\n") + "\n";
}

const only = process.argv[2];
mkdirSync(new URL("../data/", import.meta.url), { recursive: true });
for (const [key, preset] of Object.entries(PRESETS)) {
  if (only && only !== key) continue;
  const ds = generate(preset);
  const base = new URL(`../data/${preset.file}`, import.meta.url).pathname;
  writeFileSync(`${base}.json`, JSON.stringify(ds, null, 2) + "\n");
  writeFileSync(`${base}.csv`, toCsv(ds));
  console.log(`${preset.file}: ${ds.events.length} events, ${ds.events[0].timestamp} → ${ds.events.at(-1).timestamp}`);
}
