// Generates reproducible, explicitly FICTIONAL lightning datasets for testing the studio.
// Nothing here was detected by any sensor. Storm cells are simple moving Gaussian clusters
// with a triangular activity profile; the fixed seed makes every run byte-identical.
//
// Usage: node scripts/generate-sample.js            (writes all presets to data/)
//        node scripts/generate-sample.js ankara     (one preset)
import { writeFileSync, mkdirSync } from "node:fs";
import { toIsoWithOffset } from "../src/core/parse.js";

function mulberry32(seed) {
  return function () {
    seed |= 0; seed = (seed + 0x6d2b79f5) | 0;
    let t = Math.imul(seed ^ (seed >>> 15), 1 | seed);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

